#include <stdio.h>  

int main() {
    // Declare and initialize cost per poster and number of posters
    int costPerPoster = 25;
    int numberOfPosters = 20;

    // Calculate the total cost using multiplication operator
    int totalCost = costPerPoster * numberOfPosters;

    // Print the total printing cost 
    printf("Total Printing Cost = %d\n", totalCost);

    return 0;  
}