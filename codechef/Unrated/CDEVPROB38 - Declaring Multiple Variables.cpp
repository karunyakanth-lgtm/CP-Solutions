#include <stdio.h>

int main() {
    // Declare variables of different types in a single line
    int age = 25, height = 168;   // Declare an integer for age and height and assign a value
    long num = 9876543210, code = 111111;   // Declare a long for contact number and PIN Code of a person and assign a value
    

    // Print the values of the variables
    printf("Age: %d\n", age);
    printf("Height: %d cm\n", height);   
    printf("Contact Number: %ld\n", num);      
    printf("PIN Code: %ld", code);

    return 0;
}